import Foundation

/// The toolchains a workspace can combine.
enum ProjectToolchain: String, CaseIterable, Sendable, Identifiable {
    case flutter, cmake, cargo

    var id: String { rawValue }

    /// The display name.
    var title: String {
        switch self {
        case .flutter: "Flutter"
        case .cmake: "C++"
        case .cargo: "Rust"
        }
    }
}

/// One project found in the workspace: a Flutter or Dart package, a CMake project, or a Cargo root.
struct ProjectComponent: Equatable, Sendable, Identifiable {
    /// What kind of project the component is.
    enum Kind: String, Sendable {
        case flutterApp, flutterPlugin, flutterPackage, dartPackage
        case cmakeProject, platformRunner
        case cargoWorkspace, cargoPackage

        /// The toolchain that builds the component.
        var toolchain: ProjectToolchain {
            switch self {
            case .flutterApp, .flutterPlugin, .flutterPackage, .dartPackage: .flutter
            case .cmakeProject, .platformRunner: .cmake
            case .cargoWorkspace, .cargoPackage: .cargo
            }
        }

        /// The display name.
        var title: String {
            switch self {
            case .flutterApp: String(localized: "Flutter app")
            case .flutterPlugin: String(localized: "Flutter plugin")
            case .flutterPackage: String(localized: "Flutter package")
            case .dartPackage: String(localized: "Dart package")
            case .cmakeProject: String(localized: "CMake project")
            case .platformRunner: String(localized: "Platform runner")
            case .cargoWorkspace: String(localized: "Cargo workspace")
            case .cargoPackage: String(localized: "Cargo package")
            }
        }
    }

    /// How the component relates to the workspace.
    enum Role: String, Sendable {
        /// Built and served by language servers; the workspace's own project.
        case primary
        /// Part of the project but not its root, such as a package in `packages/`.
        case member
        /// Vendored code (`third_party/`, `vendor/`, …); listed but not built.
        case thirdParty
        /// Generated by a tool, such as Flutter's Windows and Linux runners.
        case generated

        /// The display name.
        var title: String {
            switch self {
            case .primary: String(localized: "Primary")
            case .member: String(localized: "Member")
            case .thirdParty: String(localized: "Third party")
            case .generated: String(localized: "Generated")
            }
        }
    }

    var kind: Kind
    var role: Role
    var name: String
    /// A version or short description, when known.
    var detail: String?
    var directory: URL
    /// The folder relative to the workspace, `.` for the workspace itself.
    var relativePath: String

    var id: String { "\(kind.rawValue):\(relativePath)" }
}

/// A build relationship between two components, detected from file contents.
struct ProjectLink: Equatable, Sendable, Identifiable {
    /// The component that builds or depends on the other.
    var source: ProjectComponent.ID
    /// The component being built or depended on.
    var target: ProjectComponent.ID
    /// What the link means, such as "builds" or "depends on".
    var summary: String
    /// The file the link was read from, relative to the workspace.
    var evidence: String

    var id: String { "\(source)->\(target)" }
}

/// A configuration file found in the workspace, for the Project Files list.
struct ProjectConfigurationFile: Equatable, Hashable, Sendable {
    var toolchain: ProjectToolchain
    /// The path relative to the workspace.
    var relativePath: String
}

/// Everything a workspace folder contains, read from configuration files only.
///
/// ``scan(workspace:)`` walks the folder (bounded depth, skipping build output, caches and hidden
/// folders) and never runs a tool, so it is safe on any folder. It touches many files; call it
/// off the main actor.
struct ProjectInventory: Equatable, Sendable {
    /// The workspace folder.
    var workspaceDirectory: URL
    /// Components in display order: Flutter, CMake, Cargo; primary before others.
    var components: [ProjectComponent] = []
    var links: [ProjectLink] = []
    /// The Flutter project at the workspace root, if any.
    var flutter: FlutterProject?
    /// Cargo roots that are not third party, in discovery order.
    var cargoRoots: [CargoRoot] = []
    /// Configuration files of the workspace's own components.
    var configurationFiles: [ProjectConfigurationFile] = []

    /// How deep below the workspace the scan looks.
    static let maxDepth = 4
    /// Folders never scanned: build output, tool caches, dependency trees and generated files.
    static let skippedFolderNames: Set<String> = [
        "build", "target", "node_modules", "Pods", "ephemeral", "DerivedData", "out", "CMakeFiles"
    ]
    /// Folder names that hold vendored code.
    static let thirdPartyFolderNames: Set<String> = [
        "third_party", "thirdparty", "third-party", "3rdparty", "vendor", "external", "deps"
    ]

    /// The toolchains of the workspace's primary components.
    var toolchains: [ProjectToolchain] {
        ProjectToolchain.allCases.filter { toolchain in
            components.contains { $0.kind.toolchain == toolchain && $0.role == .primary }
        }
    }

    /// Whether the workspace combines two or more toolchains.
    var isHybrid: Bool { toolchains.count > 1 }

    /// The component with `id`.
    func component(_ id: ProjectComponent.ID) -> ProjectComponent? {
        components.first { $0.id == id }
    }

    // MARK: - Scanning

    /// Scans a workspace folder.
    static func scan(workspace: URL) -> Self {
        let workspace = workspace.standardizedFileURL
        var inventory = Self(workspaceDirectory: workspace)
        let found = walk(workspace)
        inventory.flutter = FlutterProject.load(at: workspace)
        inventory.addDartPackages(found.pubspecFolders)
        inventory.addCMakeProjects(found.cmakeFolders)
        inventory.addCargoRoots()
        inventory.detectLinks()
        inventory.collectConfigurationFiles()
        return inventory
    }

    /// A folder's path relative to the workspace, `.` for the workspace itself.
    func relativePath(of url: URL) -> String {
        Self.relativePath(of: url, in: workspaceDirectory)
    }

    static func relativePath(of url: URL, in workspace: URL) -> String {
        FlutterProject.relativePath(of: url, in: workspace)
    }

    func role(for directory: URL) -> ProjectComponent.Role {
        let components = relativePath(of: directory).split(separator: "/").map(String.init)
        return components.contains(where: Self.thirdPartyFolderNames.contains) ? .thirdParty : .primary
    }

    private struct WalkResult {
        var pubspecFolders: [URL] = []
        var cmakeFolders: [URL] = []
    }

    /// Breadth-first walk collecting folders that hold a pubspec or a CMake list file.
    private static func walk(_ workspace: URL) -> WalkResult {
        var result = WalkResult()
        var level = [workspace]
        var visited = 0
        let fileManager = FileManager.default
        for depth in 0...maxDepth {
            var next: [URL] = []
            for folder in level {
                visited += 1
                if visited > 6_000 { return result }
                if fileManager.fileExists(atPath: folder.appending(path: PubspecParser.fileName).path) {
                    result.pubspecFolders.append(folder)
                }
                if CMakeProject.isCMakeProject(at: folder) {
                    result.cmakeFolders.append(folder)
                }
                guard depth < maxDepth else { continue }
                next += subfolders(of: folder)
            }
            level = next
        }
        return result
    }

    static func subfolders(of folder: URL) -> [URL] {
        let keys: [URLResourceKey] = [.isDirectoryKey, .isSymbolicLinkKey]
        let children = (try? FileManager.default.contentsOfDirectory(
            at: folder,
            includingPropertiesForKeys: keys,
            options: [.skipsHiddenFiles, .skipsPackageDescendants]
        )) ?? []
        return children
            .filter { child in
                guard let values = try? child.resourceValues(forKeys: Set(keys)),
                      values.isDirectory == true, values.isSymbolicLink != true else { return false }
                return !skippedFolderNames.contains(child.lastPathComponent)
            }
            .map(\.standardizedFileURL)
            .sorted { $0.path < $1.path }
    }

    /// The configuration file names whose change should trigger a rescan.
    static let watchedFileNames: Set<String> = [
        PubspecParser.fileName, "pubspec.lock", AnalysisOptions.fileName, FlutterMetadata.fileName,
        "package_config.json", "build.dart", "ffigen.yaml",
        "CMakeLists.txt", "CMakePresets.json", "CMakeUserPresets.json",
        CargoManifest.fileName, "rust-toolchain", "rust-toolchain.toml", "config.toml", "build.rs"
    ]
}
